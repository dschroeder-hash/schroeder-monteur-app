import { dark, light, sizing, typography, type SemanticColors } from './tokens.js';

const vars = (c: SemanticColors) =>
  Object.entries(c)
    .map(([k, v]) => `  --color-${k}: ${v};`)
    .join('\n');

/**
 * Generates the theme stylesheet: CSS variables for light/dark plus a Tailwind v4 `@theme inline` block,
 * so utilities like `bg-primary` or `text-text-muted` resolve to the active theme.
 */
export function buildThemeCss(): string {
  const keys = Object.keys(light);
  return `/* Generated by @schroeder/ui – do not edit. Source: packages/ui/src/tokens.ts */
@font-face {
  font-family: 'Delta Jaeger';
  font-style: italic;
  font-weight: 500;
  font-display: swap;
  /* Webfont licence open (OFFENE-PUNKTE OP-04): installed fonts only. Once licensed, add
     url('/fonts/delta-jaeger-medium-italic.woff2') format('woff2') – a missing file costs a 404 on every page. */
  src: local('Delta Jaeger Medium Italic'), local('DeltaJaeger-MediumItalic');
}
@font-face {
  font-family: 'Helvetica Neue Heavy';
  font-style: italic;
  font-weight: 800;
  font-display: swap;
  /* Once licensed, add url('/fonts/helvetica-neue-heavy-italic.woff2') format('woff2'). */
  src: local('Helvetica Neue Heavy Italic'), local('HelveticaNeue-HeavyItalic');
}

:root {
${vars(light)}
  --font-headline: ${typography.headline};
  --font-emphasis: ${typography.emphasis};
  --font-body: ${typography.body};
  --touch-min: ${sizing.touchMin};
  --touch-large: ${sizing.touchLarge};
  --radius: ${sizing.radius};
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${vars(dark).replace(/^/gm, '  ')}
    color-scheme: dark;
  }
}

:root[data-theme='dark'] {
${vars(dark)}
  color-scheme: dark;
}

@theme inline {
${keys.map((k) => `  --color-${k}: var(--color-${k});`).join('\n')}
  --font-headline: var(--font-headline);
  --font-emphasis: var(--font-emphasis);
  --font-sans: var(--font-body);
  --spacing-touch: var(--touch-min);
  --spacing-touch-lg: var(--touch-large);
  --radius-card: var(--radius);
}
`;
}
